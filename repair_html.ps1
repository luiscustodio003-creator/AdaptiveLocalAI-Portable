
$ErrorActionPreference = "Stop"

$path = "D:\Dev\Python\AdaptiveLocalAI-Portable\src\ui\index.html"
$utf8 = New-Object System.Text.UTF8Encoding($false, $true)

if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
    throw "HTML file not found."
}

$original = [System.IO.File]::ReadAllText($path, $utf8)
$result = $original

function U([int[]]$codes) {
    return -join ($codes | ForEach-Object { [char]$_ })
}

$bad = @(
    (U @(0x616A,0x7573,0x74,0xC3,0xA1,0x76,0x65,0x6C))
)

# Build replacements from Unicode code points to avoid
# relying on accented characters typed into the script.
$pairs = @(
    @((U @(0x436F,0x6E,0x66,0x69,0x67,0x75,0x72,0x61,0xC3,0xA7,0xC3,0xA3,0x6F)), (U @(0x43,0x6F,0x6E,0x66,0x69,0x67,0x75,0x72,0x61,0xE7,0xE3,0x6F))),
    @((U @(0x44,0x69,0x61,0x67,0x6E,0xC3,0xB3,0x73,0x74,0x69,0x63,0x6F)), (U @(0x44,0x69,0x61,0x67,0x6E,0xF3,0x73,0x74,0x69,0x63,0x6F))),
    @((U @(0x64,0x69,0x73,0x70,0x6F,0x6E,0xC3,0xAD,0x76,0x65,0x69,0x73)), (U @(0x64,0x69,0x73,0x70,0x6F,0x6E,0xED,0x76,0x65,0x69,0x73))),
    @((U @(0x64,0x69,0x73,0x70,0x6F,0x6E,0xC3,0xAD,0x76,0x65,0x6C)), (U @(0x64,0x69,0x73,0x70,0x6F,0x6E,0xED,0x76,0x65,0x6C))),
    @((U @(0x6E,0xC3,0xBA,0x63,0x6C,0x65,0x6F,0x73)), (U @(0x6E,0xFA,0x63,0x6C,0x65,0x6F,0x73))),
    @((U @(0x6D,0xC3,0xA1,0x78,0x2E)), (U @(0x6D,0xE1,0x78,0x2E))),
    @((U @(0x47,0x65,0x72,0x61,0xC3,0xA7,0xC3,0xA3,0x6F)), (U @(0x47,0x65,0x72,0x61,0xE7,0xE3,0x6F))),
    @((U @(0x4E,0xC3,0xA3,0x6F,0x20,0x68,0xC3,0xA1)), (U @(0x4E,0xE3,0x6F,0x20,0x68,0xE1))),
    @((U @(0x70,0xC3,0xA1,0x67,0x69,0x6E,0x61)), (U @(0x70,0xE1,0x67,0x69,0x6E,0x61))),
    @((U @(0x69,0x6E,0x64,0x69,0x73,0x70,0x6F,0x6E,0xC3,0xAD,0x76,0x65,0x6C)), (U @(0x69,0x6E,0x64,0x69,0x73,0x70,0x6F,0x6E,0xED,0x76,0x65,0x6C))),
    @((U @(0x63,0x6F,0x6E,0x74,0x65,0xC3,0xBA,0x64,0x6F)), (U @(0x63,0x6F,0x6E,0x74,0x65,0xFA,0x64,0x6F))),
    @((U @(0x63,0x61,0x72,0x74,0xC3,0xA3,0x6F)), (U @(0x63,0x61,0x72,0x74,0xE3,0x6F))),
    @((U @(0x6C,0x69,0x67,0x61,0xC3,0xA7,0xC3,0xA3,0x6F)), (U @(0x6C,0x69,0x67,0x61,0xE7,0xE3,0x6F))),
    @((U @(0x61,0x75,0x74,0x6F,0x6D,0xC3,0xA1,0x74,0x69,0x63,0x61)), (U @(0x61,0x75,0x74,0x6F,0x6D,0xE1,0x74,0x69,0x63,0x61))),
    @((U @(0x50,0x72,0x65,0x66,0x65,0x72,0xC3,0xAA,0x6E,0x63,0x69,0x61,0x73)), (U @(0x50,0x72,0x65,0x66,0x65,0x72,0xEA,0x6E,0x63,0x69,0x61,0x73)))
)

foreach ($pair in $pairs) {
    $result = $result.Replace($pair[0], $pair[1])
}

# Replace common corrupted punctuation and menu symbol.
$result = $result.Replace((U @(0xC3,0xA2,0xE2,0x82,0xAC,0xC2,0x94)), (U @(0x2014)))
$result = $result.Replace((U @(0xC3,0xA2,0xE2,0x82,0xAC,0xC2,0xA6)), (U @(0x2026)))
$result = $result.Replace((U @(0xC3,0xA2,0xCB,0x9C,0xC2,0xB0)), (U @(0x2630)))
$result = $result.Replace((U @(0xC3,0x82,0xC2,0xB7)), (U @(0xB7)))

if ($result -ceq $original) {
    Write-Host "No matching text was changed. Original preserved." -ForegroundColor Yellow
    exit 0
}

$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$backup = "$path.bak-before-text-repair-$stamp"
$temp = "$path.repair-tmp"

Copy-Item -LiteralPath $path -Destination $backup
[System.IO.File]::WriteAllText($temp, $result, (New-Object System.Text.UTF8Encoding($false)))

$check = [System.IO.File]::ReadAllText($temp, $utf8)
if ($check -cne $result) {
    Remove-Item -LiteralPath $temp -Force
    throw "UTF-8 verification failed. Original HTML preserved."
}

Move-Item -LiteralPath $temp -Destination $path -Force
Write-Host "Repair completed. Backup: $backup" -ForegroundColor Green
